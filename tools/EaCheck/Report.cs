using System.Text;

namespace EaCheck;

sealed record Finding(Dep Dep, Problem Problem)
{
    public bool TestOnly => Dep.TestOnly;
    public string Features => string.Join(", ", Dep.FeatureNames.OrderBy(x => x));
}

static class Report
{
    private static readonly string[] Order = { "Harmony", "Reflection", "Method", "Field", "Type", "Implements", "Enum value", "Scene" };
    private static readonly Dictionary<string, string> Titles = new()
    {
        ["Harmony"] = "Hooks", ["Reflection"] = "Lookups by name", ["Method"] = "Methods", ["Field"] = "Fields", ["Type"] = "Types",
        ["Implements"] = "Implements/derives", ["Enum value"] = "Enum values", ["Scene"] = "Scenes",
    };

    private static string Esc(string s) => s.Replace("|", "\\|").Replace("\n", " ");
    private static string Code(string s) => "`" + s.Replace("`", "'") + "`";

    public static string Where(IEnumerable<Use> uses, int max = 4)
    {
        var list = uses.OrderBy(u => u.TestOnly).ThenBy(u => u.File).ThenBy(u => u.Line).ToList();
        var shown = list.Take(max).Select(u => u.Line > 0 ? $"{u.File}:{u.Line}" : u.File);
        return string.Join(", ", shown) + (list.Count > max ? $" (+{list.Count - max})" : "");
    }

    private static string Lines(IEnumerable<Use> uses) =>
        string.Join(", ", uses.Where(u => u.Line > 0).Select(u => u.Line).Distinct().OrderBy(x => x));

    public static string Inventory(Inventory inv, GameBuild baseline)
    {
        var deps = inv.Deps.Values.ToList();
        var sb = new StringBuilder();
        sb.AppendLine("# EmbervilleMP: game dependency inventory");
        sb.AppendLine();
        sb.AppendLine($"Generated by `scripts\\ea-check.ps1` on {DateTime.Now:yyyy-MM-dd HH:mm} from `{System.IO.Path.GetFileName(inv.PluginPath)}`");   // (no local folders in a committed file)
        sb.AppendLine($"against {baseline.Describe()}.");
        sb.AppendLine();
        sb.AppendLine("Everything the compiled plugin needs from the game, read from its IL (and pdb for file:line):");
        sb.AppendLine("**hooks** (Harmony targets and the parameters our patches bind by name), **lookups by name** (AccessTools, reflection,");
        sb.AppendLine("Traverse, `tools/EaCheck/ea-hints.txt`), every **method / field / type** referenced in the game's assemblies,");
        sb.AppendLine("classes of ours that **implement** game interfaces, **enum values** compiled in as numbers (from our sources), and **scene names**.");
        sb.AppendLine("`ea-check.ps1 -GameDir <build>` checks all of it against another build.");
        sb.AppendLine();

        // summary per feature
        sb.AppendLine("## Summary");
        sb.AppendLine();
        sb.AppendLine("| Feature | Code | " + string.Join(" | ", Order.Select(o => Titles[o])) + " |");
        sb.AppendLine("|---|---|" + string.Concat(Order.Select(_ => "---:|")));
        var features = deps.SelectMany(d => d.Uses.Select(u => u.Feature)).Distinct()
            .OrderBy(f => f == "Self-tests & dev harness" ? 1 : 0).ThenBy(f => f).ToList();
        foreach (var f in features)
        {
            bool test = f == "Self-tests & dev harness";
            var mine = deps.Where(d => d.Uses.Any(u => u.Feature == f)).ToList();
            sb.AppendLine($"| {f} | {(test ? "test-only" : "runtime")} | " + string.Join(" | ", Order.Select(o => mine.Count(d => d.Category == o))) + " |");
        }
        sb.AppendLine("| **Total (unique)** | | " + string.Join(" | ", Order.Select(o => $"**{deps.Count(d => d.Category == o)}**")) + " |");
        sb.AppendLine();
        var byAsm = deps.Where(d => d.Assembly != "").GroupBy(d => d.Assembly).OrderByDescending(g => g.Count());
        sb.AppendLine("By game assembly: " + string.Join(", ", byAsm.Select(g => $"{g.Key} {g.Count()}")) + ".");
        sb.AppendLine();

        // hooks
        sb.AppendLine("## Hooks (Harmony)");
        sb.AppendLine();
        sb.AppendLine("Each patch class is applied on its own; a missing target or parameter disables that class only (`[patch]` in the log).");
        sb.AppendLine();
        sb.AppendLine("| Patch class | Feature | Target | Patch methods (parameters bound by name) | File |");
        sb.AppendLine("|---|---|---|---|---|");
        foreach (var h in deps.OfType<HarmonyPatchDep>().OrderBy(h => h.Uses[0].File).ThenBy(h => h.PatchClass.Name))
            sb.AppendLine($"| {h.PatchClass.Name} | {h.Uses[0].Feature} | {Esc(string.Join("<br>", h.Targets.Select(t => Code(t.Spec.Describe()))))} | {Esc(h.Extra)} | {Where(h.Uses)} |");
        sb.AppendLine();

        // lookups
        sb.AppendLine("## Lookups by name");
        sb.AppendLine();
        sb.AppendLine("| Lookup | How | Used at |");
        sb.AppendLine("|---|---|---|");
        foreach (var d in deps.Where(d => d.Category == "Reflection").OrderBy(d => d.Display))
            sb.AppendLine($"| {Code(d.Display)} | {Esc(d.Extra)} | {Where(d.Uses, 8)} |");
        sb.AppendLine();

        // enums
        sb.AppendLine("## Enum values compiled into the plugin");
        sb.AppendLine();
        sb.AppendLine("C# bakes enum members in as numbers: if the game renumbers them, the built mod silently means something else.");
        sb.AppendLine();
        sb.AppendLine("| Member | Value | Used at |");
        sb.AppendLine("|---|---|---|");
        foreach (var d in deps.Where(d => d.Category == "Enum value").OrderBy(d => d.TestOnly).ThenBy(d => d.Display))
            sb.AppendLine($"| {Code(d.Display)} | {Esc(d.Extra)} | {Where(d.Uses, 6)} |");
        sb.AppendLine();

        // scenes
        sb.AppendLine("## Scene names in our code");
        sb.AppendLine();
        sb.AppendLine("Build scenes (baseline): " + (baseline.Scenes == null ? "unknown" : string.Join(", ", baseline.Scenes)) + ".");
        sb.AppendLine();
        sb.AppendLine("| Scene | Used at |");
        sb.AppendLine("|---|---|");
        foreach (var d in deps.OfType<SceneDep>().OrderBy(d => d.Scene))
            sb.AppendLine($"| {d.Scene} | {Where(d.Uses, 12)} |");
        sb.AppendLine();

        // by feature / file
        sb.AppendLine("## By feature and file");
        sb.AppendLine();
        foreach (var f in features)
        {
            sb.AppendLine($"### {f}");
            sb.AppendLine();
            var files = deps.SelectMany(d => d.Uses).Where(u => u.Feature == f).Select(u => u.File).Distinct().OrderBy(x => x);
            foreach (var file in files)
            {
                sb.AppendLine($"#### `{file}`");
                sb.AppendLine();
                foreach (var cat in Order)
                {
                    var here = deps.Where(d => d.Category == cat && d.Uses.Any(u => u.File == file)).OrderBy(d => d.Display).ToList();
                    if (here.Count == 0) continue;
                    if (cat == "Type")
                    {
                        sb.AppendLine($"- **Types ({here.Count})**: " + string.Join(", ", here.Select(d => Code(d.Display))));
                        continue;
                    }
                    sb.AppendLine($"- **{Titles[cat]} ({here.Count})**");
                    foreach (var d in here)
                    {
                        var lines = Lines(d.Uses.Where(u => u.File == file));
                        string extra = d.Extra != "" ? " (" + d.Extra + ")" : "";
                        sb.AppendLine($"  - {Code(d.Display)}{extra}{(lines == "" ? "" : " — line " + lines)}");
                    }
                }
                sb.AppendLine();
            }
        }

        if (inv.Warnings.Count > 0)
        {
            sb.AppendLine("## Scanner warnings");
            sb.AppendLine();
            foreach (var w in inv.Warnings) sb.AppendLine("- " + w);
            sb.AppendLine();
        }
        return sb.ToString();
    }

    public static string Check(Inventory inv, List<Finding> findings, GameBuild target, GameBuild baseline)
    {
        var sb = new StringBuilder();
        var problems = findings.Where(f => f.Problem.Severity != Severity.Info)
            .OrderBy(f => f.Problem.Severity).ThenBy(f => f.TestOnly).ThenBy(f => f.Features).ThenBy(f => f.Problem.Title).ToList();
        var infos = findings.Where(f => f.Problem.Severity == Severity.Info).ToList();
        bool self = ReferenceEquals(target, baseline);

        sb.AppendLine("# ea-check report");
        sb.AppendLine();
        sb.AppendLine($"- Generated: {DateTime.Now:yyyy-MM-dd HH:mm}");
        sb.AppendLine($"- Plugin: `{inv.PluginPath}`");
        sb.AppendLine($"- Baseline (the build the mod targets): {baseline.Describe()}");
        sb.AppendLine($"- Checked against: {(self ? "the baseline itself (self-check)" : target.Describe())}");
        sb.AppendLine($"- Dependencies checked: {inv.Deps.Count}");
        sb.AppendLine();
        if (problems.Count == 0)
            sb.AppendLine($"**No problems**: every one of the {inv.Deps.Count} dependencies resolves in this build.");
        else
        {
            var bySev = problems.GroupBy(p => p.Problem.Severity).OrderBy(g => g.Key).Select(g => $"{g.Count()} {g.Key.ToString().ToLowerInvariant()}");
            int runtime = problems.Count(p => !p.TestOnly);
            sb.AppendLine($"**{problems.Count} problems** ({string.Join(", ", bySev)}); {runtime} in runtime code, {problems.Count - runtime} in test-only code.");
        }
        sb.AppendLine();
        sb.AppendLine("Severity: **Critical** = a class of ours fails to load (whatever touches it breaks); **High** = a hook is skipped");
        sb.AppendLine("(feature off, `[patch]` in the log) or a call throws when it runs; **Medium** = silently wrong or degraded.");
        sb.AppendLine("Fix in that order; then rebuild against the new build and re-run `test-all.ps1`.");
        sb.AppendLine();

        if (problems.Count > 0)
        {
            sb.AppendLine("## Features affected");
            sb.AppendLine();
            sb.AppendLine("| Feature | Critical | High | Medium |");
            sb.AppendLine("|---|---:|---:|---:|");
            var feats = problems.SelectMany(p => p.Dep.FeatureNames.Select(f => (f, p.Problem.Severity))).GroupBy(x => x.f)
                .OrderBy(g => g.Min(x => x.Severity)).ThenByDescending(g => g.Count());
            foreach (var g in feats)
                sb.AppendLine($"| {g.Key} | {g.Count(x => x.Severity == Severity.Critical)} | {g.Count(x => x.Severity == Severity.High)} | {g.Count(x => x.Severity == Severity.Medium)} |");
            sb.AppendLine();

            sb.AppendLine("## Problems, most severe first");
            sb.AppendLine();
            sb.AppendLine("| # | Severity | Feature | Code | Problem | Detail | Used at |");
            sb.AppendLine("|---:|---|---|---|---|---|---|");
            int n = 1;
            foreach (var p in problems)
                sb.AppendLine($"| {n++} | {p.Problem.Severity} | {Esc(p.Features)} | {(p.TestOnly ? "test-only" : "runtime")} | {Esc(p.Problem.Title)} | {Esc(p.Problem.Detail)} | {Where(p.Dep.Uses)} |");
            sb.AppendLine();
        }

        sb.AppendLine("## Notes");
        sb.AppendLine();
        if (!self)
        {
            if (baseline.Scenes != null && target.Scenes != null)
            {
                var added = target.Scenes.Except(baseline.Scenes).ToList();
                var removed = baseline.Scenes.Except(target.Scenes).ToList();
                sb.AppendLine($"- Scenes in this build: {string.Join(", ", target.Scenes)}.");
                if (added.Count > 0) sb.AppendLine($"- **New scenes** (survey them): {string.Join(", ", added)}.");
                if (removed.Count > 0) sb.AppendLine($"- **Scenes gone**: {string.Join(", ", removed)}.");
            }
            var newAsm = target.GameAssemblies.Except(baseline.GameAssemblies).OrderBy(x => x).ToList();
            var goneAsm = baseline.GameAssemblies.Except(target.GameAssemblies).OrderBy(x => x).ToList();
            if (newAsm.Count > 0) sb.AppendLine($"- New assemblies: {string.Join(", ", newAsm)}.");
            if (goneAsm.Count > 0) sb.AppendLine($"- Assemblies gone: {string.Join(", ", goneAsm)} (if the plugin's .csproj references one, the build breaks).");
        }
        foreach (var i in infos) sb.AppendLine($"- {Esc(i.Problem.Title)}: {Esc(i.Problem.Detail)} ({Where(i.Dep.Uses)})");
        foreach (var w in inv.Warnings) sb.AppendLine("- scanner: " + w);
        if (self && infos.Count == 0 && inv.Warnings.Count == 0) sb.AppendLine("- none");
        sb.AppendLine();
        return sb.ToString();
    }
}
